const dialog = document.getElementById("file-format-dialog");

if (dialog) {
  const path = document.getElementById("format-path");
  const title = document.getElementById("format-title");
  const intro = document.getElementById("format-intro");
  const facts = document.getElementById("format-facts");
  const example = document.getElementById("format-example");
  const exampleLabel = document.getElementById("format-example-label");
  const exampleCode = document.getElementById("format-example-code");
  const note = document.getElementById("format-note");

  document.querySelectorAll(".sd-file[data-format]").forEach((button) => {
    button.addEventListener("click", () => {
      const format = formats[button.dataset.format];
      if (!format) return;

      path.textContent = format.path;
      title.textContent = format.title;
      intro.textContent = format.intro;
      facts.replaceChildren(...format.facts.map((text) => {
        const item = document.createElement("li");
        item.textContent = text;
        return item;
      }));

      example.hidden = !format.example;
      exampleLabel.textContent = format.exampleLabel || "Example";
      exampleCode.textContent = format.example || "";
      note.hidden = !format.note;
      note.textContent = format.note || "";

      dialog.scrollTop = 0;
      dialog.showModal();
    });
  });

  document.getElementById("format-close").addEventListener("click", () => dialog.close());
  dialog.addEventListener("click", (event) => {
    if (event.target !== dialog) return;
    const box = dialog.getBoundingClientRect();
    const outside = event.clientX < box.left || event.clientX > box.right ||
      event.clientY < box.top || event.clientY > box.bottom;
    if (outside) dialog.close();
  });
}
